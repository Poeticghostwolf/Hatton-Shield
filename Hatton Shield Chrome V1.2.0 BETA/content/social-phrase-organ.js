  function normalize(value){
    let s=String(value||'').slice(0,MAX_INPUT);
    try{s=s.normalize('NFKC')}catch(_e){}
    // Hashtags belong to the hashtag organ. Remove the complete token here so one
    // source cannot be counted once as a hashtag and again as a plain phrase.
    s=s.replace(/#[a-z0-9_]{2,64}/gi,' ')
       .toLowerCase()
       .replace(/[\u200b-\u200f\u2060\ufeff]/g,' ')
       .replace(/[\u2010-\u2015\u2212_./\\:|~*]+/g,' ')
       .replace(/[^a-z0-9+]+/g,' ')
       .replace(/\s+/g,' ')
       .trim();
    return s.slice(0,MAX_INPUT);
  }
  function phrasePresent(text,phrase){
    if(!text||!phrase)return false;
    return (` ${text} `).includes(` ${phrase} `);
  }
  function hits(text,list){
    const out=[];
    for(const p of list){if(phrasePresent(text,p)){out.push(p);if(out.length>=MAX_HITS)break;}}
    return out;
  }
  function uniq(a){return [...new Set(a)].slice(0,MAX_HITS);}
  function escapeRe(s){return s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&').replace(/\s+/g,'\\s+');}
  const TOOL_ALT=[...FAMILIES.tool].sort((a,b)=>b.length-a.length).map(escapeRe).join('|');
  const CREATION_RE=new RegExp(`(?:\\b(?:made|created|generated|produced|rendered|animated|edited|designed)\\s+(?:with|using|by|in)\\s+(${TOOL_ALT})\\b)|(?:\\b(?:using|with)\\s+(${TOOL_ALT})\\s+(?:to\\s+)?(?:make|create|generate|render|animate|edit|produce)\\b)|(?:\\b(${TOOL_ALT})\\s+(?:generated|created|made|rendered|animated|produced)\\b)`,'i');
  const PROMO_RE=new RegExp(`(?:\\b(?:try|download|get|use)\\s+(?:the\\s+)?(${TOOL_ALT})\\s+(?:now|today|free|online)\\b)|(?:\\b(${TOOL_ALT})\\s+(?:generator|app|tool)\\s+(?:free|online|now)\\b)`,'i');
  const CTA_RE=/\b(?:try|use|download|get|free|online|app|tool|generator|template|link in bio|create your own|make your own|generate your own)\b/i;

